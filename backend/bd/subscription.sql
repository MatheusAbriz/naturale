create table subscription(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id int not null,
    plan varchar(10) not null check (plan in ('essential','extra','deluxe')),
    status varchar(20) not null default 'pending'
        check (status in ('pending','active','canceled','expired')),
    payment_method varchar(20) null,
    mp_preference_id varchar(64) null,
    mp_preapproval_id varchar(64) null,
    current_period_end timestamp null,
    created_at timestamp not null default now(),
    updated_at timestamp not null default now(),

    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

create unique index subscription_user_id_uni on subscription(user_id);

create table subscription_payment(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id int not null,
    mp_payment_id varchar(64) not null UNIQUE,
    amount numeric(10,2) not null,
    method varchar(20) not null,
    status varchar(20) not null,
    payload jsonb not null,
    created_at timestamp not null default now(),

    FOREIGN KEY (subscription_id) REFERENCES subscription(id) ON DELETE CASCADE
);

create table chatbot_usage(
    user_id int not null,
    usage_day date not null,
    questions_used int not null default 0,

    PRIMARY KEY (user_id, usage_day),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

update subscription
set status = 'expired', updated_at = now()
where status = 'active' and current_period_end <= now();
