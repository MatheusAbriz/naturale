create table favorite_collection(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id int not null,
    name varchar(60) not null,
    created_at timestamp not null default now(),

    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

create index favorite_collection_user_id_idx on favorite_collection(user_id);

create table favorite_collection_post(
    collection_id int not null,
    post_id int not null,
    created_at timestamp not null default now(),

    PRIMARY KEY (collection_id, post_id),
    FOREIGN KEY (collection_id) REFERENCES favorite_collection(id) ON DELETE CASCADE,
    FOREIGN KEY (post_id) REFERENCES post(id) ON DELETE CASCADE
);
